namespace BoldlyGrow\Okta;

use BoldlyGrow\Okta\Exceptions\ConfigurationException;
use Illuminate\Http\Client\Response;
use Illuminate\Support\Arr;
use Illuminate\Support\Str;

/**
 * OAuth 2.0 Demonstrating Proof of Possession (DPoP) Proof Generator
 *
 * @author Jeff Martin
 *
 * When an Okta service app has "Require Demonstrating Proof of Possession (DPoP) header in token requests" enabled,
 * the access token is bound to a key pair held by the client. Every token request and every API request must then
 * carry a `DPoP` header containing a short-lived JWT (the proof) that is signed with that key and bound to the HTTP
 * method and URL of the request. A stolen DPoP-bound access token is useless without the private key.
 *
 * @link https://datatracker.ietf.org/doc/html/rfc9449
 *
 * KEY LIFECYCLE
 * The DPoP key pair is ephemeral and separate from the private_key_jwt client authentication key. A new key pair is
 * generated by ApiToken each time an access token is minted, and is cached (encrypted) alongside the access token for
 * the lifetime of the token since every request that presents the token must be signed with the same key.
 *
 * NONCES
 * Okta requires a server-provided nonce in the proof. The first request without a nonce is rejected with a
 * `use_dpop_nonce` error and a `DPoP-Nonce` response header, and the request is retried with the nonce included.
 *
 * This is called from inside the ApiToken and ApiClient classes and does not need to be instantiated separately.
 */
class DpopProof
{
    public const ALGORITHM = 'RS256';

    public const JWT_TYPE = 'dpop+jwt';

    public const KEY_BITS = 2048;

    /**
     * Generate a new ephemeral RSA private key for signing DPoP proofs.
     *
     * @return string PEM-formatted RSA private key
     *
     * @throws ConfigurationException
     */
    public static function generatePrivateKey(): string
    {
        $key_resource = openssl_pkey_new([
            'private_key_type' => OPENSSL_KEYTYPE_RSA,
            'private_key_bits' => self::KEY_BITS,
        ]);

        if ($key_resource === false || openssl_pkey_export($key_resource, $private_key) === false) {
            throw new ConfigurationException(implode(' ', [
                'Okta API DPoP error.',
                '(Reason) The ephemeral DPoP key pair could not be generated.',
                '(Solution) Check that the openssl extension is available and configured.',
            ]));
        }

        return $private_key;
    }

    /**
     * Create a signed DPoP proof JWT for a single HTTP request.
     *
     * @link https://datatracker.ietf.org/doc/html/rfc9449#section-4.2
     *
     * @param  string       $private_key   PEM-formatted RSA private key from generatePrivateKey()
     * @param  string       $http_method   The HTTP method of the request (ex. `GET`, `POST`)
     * @param  string       $http_url      The full URL of the request. The query string and fragment are excluded
     *                                     from the `htu` claim per the specification, and the path is percent-decoded
     *                                     since Okta compares the claim to the decoded request URL (ex. `%40` in a
     *                                     user login).
     * @param  string|null  $nonce         The server-provided `DPoP-Nonce` response header value, when required.
     * @param  string|null  $access_token  The access token presented with the request, which adds the `ath` claim
     *                                     (SHA-256 hash of the token). Omitted for token endpoint requests.
     *
     * @throws ConfigurationException
     */
    public static function create(
        string $private_key,
        string $http_method,
        string $http_url,
        ?string $nonce = null,
        ?string $access_token = null,
    ): string {
        $key_resource = openssl_pkey_get_private($private_key);
        $key_details = $key_resource !== false ? openssl_pkey_get_details($key_resource) : false;

        if ($key_resource === false || $key_details === false) {
            throw new ConfigurationException('Okta API DPoP error. (Reason) The DPoP private key could not be parsed.');
        }

        $public_key = (string) $key_details['key'];

        $header = [
            'typ' => self::JWT_TYPE,
            'alg' => self::ALGORITHM,
            'jwk' => Arr::only(PublicKeyJwk::fromPem($public_key), ['kty', 'e', 'n']),
        ];

        $claims = array_filter([
            'htm' => Str::upper($http_method),
            'htu' => rawurldecode(Str::before(Str::before($http_url, '#'), '?')),
            'iat' => now()->getTimestamp(),
            'jti' => (string) Str::uuid(),
            'nonce' => $nonce,
            'ath' => $access_token !== null ? self::base64UrlEncode(hash('sha256', $access_token, true)) : null,
        ]);

        $signing_input = self::base64UrlEncode((string) json_encode($header, JSON_UNESCAPED_SLASHES))
            . '.' . self::base64UrlEncode((string) json_encode($claims, JSON_UNESCAPED_SLASHES));

        $signature = '';

        if (openssl_sign($signing_input, $signature, $key_resource, OPENSSL_ALGO_SHA256) === false) {
            throw new ConfigurationException('Okta API DPoP error. (Reason) The DPoP proof could not be signed.');
        }

        return $signing_input . '.' . self::base64UrlEncode($signature);
    }

    /**
     * Get the server-provided nonce if the response is a `use_dpop_nonce` challenge.
     *
     * The token endpoint returns the challenge as the `error` in the JSON body, while a resource server returns it in
     * the `WWW-Authenticate` header. Both provide the nonce to use in the `DPoP-Nonce` header.
     *
     * @link https://datatracker.ietf.org/doc/html/rfc9449#section-8
     *
     * @return string|null The nonce to include in the next proof, or null if the response is not a nonce challenge
     */
    public static function nonceChallenge(Response $response): ?string
    {
        $nonce = $response->header('DPoP-Nonce');

        if ($nonce === '') {
            return null;
        }

        $is_challenge = $response->json('error') === 'use_dpop_nonce'
            || str_contains($response->header('WWW-Authenticate'), 'use_dpop_nonce');

        return $is_challenge ? $nonce : null;
    }

    /**
     * Base64url encode without padding, per the JWS spec.
     */
    private static function base64UrlEncode(string $input): string
    {
        return rtrim(strtr(base64_encode($input), '+/', '-_'), '=');
    }
}
